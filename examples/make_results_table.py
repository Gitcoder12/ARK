"""Regenerate docs/RESULTS.md from a real benchmark run.

    python examples/make_results_table.py [--episodes 40] [--seed 42]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from ark.experiments.runner import run_benchmark


def _row(key: str, stats: dict[str, float]) -> str:
    agent, condition = key.split("__", 1)
    success = (
        f"{stats['success_rate']:.2f} "
        f"[{stats['success_ci95_low']:.2f}, {stats['success_ci95_high']:.2f}]"
    )
    return (
        f"| {agent} | {condition} | {success} | "
        f"{stats['hazard_violation_rate']:.2f} | {stats['decoy_attraction_rate']:.2f} |"
    )


def build_report(episodes: int, seed: int) -> str:
    lines = [
        "# ARK benchmark results",
        "",
        f"Generated by `examples/make_results_table.py` ({episodes} episodes per cell, "
        f"seed {seed}, random hazard layouts). Success shows rate and 95% Wilson interval.",
        "",
    ]
    for use_monitor in (False, True):
        title = "With safety monitor" if use_monitor else "No monitor"
        results = run_benchmark(
            n_episodes=episodes, seed=seed, use_monitor=use_monitor, verbose=False
        )
        lines += [
            f"## {title}",
            "",
            "| Agent | Condition | Success [95% CI] | Hazard rate | Decoy rate |",
            "|---|---|---|---|---|",
        ]
        lines += [_row(key, stats) for key, stats in results.items()]
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--episodes", type=int, default=40)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path, default=Path("docs/RESULTS.md"))
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(build_report(args.episodes, args.seed), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
